/* ЄДИНЕ місце в усій браузерній частині harness, де стоїть номер порту.
   ────────────────────────────────────────────────────────────────────────
   Проблема, яку цей файл знімає. Серверна частина читає `config.mjs`, і там
   порти конфігуруються нормально. Але оверлей (`overlay/annotator.tsx`) і
   рев'ю-сторінка (`review/fixlog.html`) виконуються в БРАУЗЕРІ, файлової
   системи не бачать, і доки порти стояли в них літералами, зміна порту в
   `harness.config.json` ламала тулзу мовчки: сервер піднімався на новому
   порту, клієнти й далі стукали на старий і показували «сервер лежить».

   Тепер порядок такий, від слабкого до сильного:

       DEFAULT_NOTES_PORT  →  /harness-ports.json  →  GET <нот>/config

   1. `DEFAULT_NOTES_PORT` — точка входу й останній рубіж. Дефолт тут узагалі
      потрібен тому, що сторінку й оверлей віддає дев-сервер проєкту-господаря,
      який про harness не знає нічого: перший запит клієнта нікуди більше піти
      не може. Значення мусить збігатися з `DEFAULTS.notesPort` у `config.mjs`
      — це та сама домовленість «з коробки», записана вдруге просто тому, що
      браузер того файлу не прочитає.
   2. `/harness-ports.json` — те саме походження, що й сторінка (той самий
      origin), тож доступне завжди, коли доступна сама сторінка. Файл пише
      `setup.mjs` і РІВНО ТОДІ, коли порти в конфізі відрізняються від
      дефолтних: інсталяція «з коробки» жодних зайвих файлів у проєкті не
      лишає, а нестандартна — сама себе оголошує, без правки клієнтів руками.
   3. `GET <нот>/config` — жива відповідь самого сервера нот. Звідти
      приїжджає порт рейтингів: його клієнт наперед не знає нізвідки, і
      вгадувати другий дефолт (щоб потім розійтись із конфігом) — рівно та
      помилка, від якої тут тікають.

   Недоступний сервер не має ламати клієнта: не відповів — лишаємось на тому,
   що вже знаємо, і кажемо про це прапорцем `live`, який обидва клієнти вже
   вміють показувати як «сервер лежить». Порт рейтингів у такому разі
   невідомий (`ratings === ''`) — і це чесніше, ніж стукати в вигаданий.

   Нуль залежностей і нуль імпортів: файл вантажать і збірником (оверлей), і
   голим `import()` зі статики (сторінка). */

/* Дефолт порту нот. Змінюєш тут — зміни й `DEFAULTS.notesPort` у config.mjs. */
export const DEFAULT_NOTES_PORT = 4747

/* Порт із чужих рук довіри не має: у відповіді сервера чи в згенерованому
   файлі може бути null, рядок або сміття, а `http://host:null` падає не там,
   де його зламали, а на першому ж fetch. */
const isPort = (v) => Number.isInteger(v) && v > 0 && v < 65536

async function getJSON(url) {
  const res = await fetch(url, { cache: 'no-store' })
  if (!res.ok) throw new Error(`HTTP ${res.status}`)
  return res.json()
}

/* Хост навмисно береться з `location`, а не з конфіга: сторінку й застосунок
   регулярно відкривають з іншої машини по LAN, де `localhost` — це вже її
   власний loopback, і кожен запит падає непрозорим «Failed to fetch». */
export async function resolveEndpoints(hostname = location.hostname) {
  let notesPort = DEFAULT_NOTES_PORT
  let ratingsPort = null

  try {
    /* Абсолютний шлях, а не './': оверлей монтується на будь-якому роуті
       застосунку, і відносний шлях означав би різний файл на різних екранах. */
    const hint = await getJSON('/harness-ports.json')
    if (isPort(hint?.notesPort)) notesPort = hint.notesPort
    if (isPort(hint?.ratingsPort)) ratingsPort = hint.ratingsPort
  } catch {
    /* Файлу немає (інсталяція на дефолтних портах) або дев-сервер віддав на
       його місце index.html — обидва випадки означають «підказки нема». */
  }

  const notes = `http://${hostname}:${notesPort}`
  let live = false
  try {
    const cfg = await getJSON(`${notes}/config`)
    /* `notesPort` із відповіді свідомо ігнорується: ми до сервера вже
       достукались, і йти після цього на інший порт — це зламати робоче
       з'єднання заради числа. Цінність там має лише порт рейтингів. */
    if (isPort(cfg?.ratingsPort)) ratingsPort = cfg.ratingsPort
    live = true
  } catch {
    /* Сервер нот лежить. Клієнт працює далі на тому, що зібрав. */
  }

  return {
    notes,
    ratings: isPort(ratingsPort) ? `http://${hostname}:${ratingsPort}` : '',
    live,
  }
}
